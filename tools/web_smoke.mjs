import { chromium } from 'file:///D:/REA/node_modules/playwright-core/index.mjs';
const browser = await chromium.launch({headless:true, executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe', args:['--enable-unsafe-swiftshader']});
const page = await browser.newPage({viewport:{width:1280,height:720}});
const errors=[];
page.on('pageerror', e=>errors.push(String(e)));
page.on('console', m=>{if(m.type()==='error') errors.push(m.text());});
await page.goto('http://127.0.0.1:8765');
await page.waitForFunction(()=>!document.querySelector('#status'), null, {timeout:60000});
await page.waitForTimeout(1200);
await page.screenshot({path:'captures/web-title.png'});
await page.mouse.click(300,478);
await page.waitForTimeout(500);
await page.keyboard.press('Escape');
await page.waitForTimeout(250);
await page.screenshot({path:'captures/web-pause.png'});
await page.keyboard.press('Escape');
await page.keyboard.press('r');
await page.waitForTimeout(500);
await page.screenshot({path:'captures/web-playing.png'});
await browser.close();
console.log(JSON.stringify({errors}));
process.exitCode=errors.length?1:0;
